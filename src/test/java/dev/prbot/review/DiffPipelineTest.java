package dev.prbot.review;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;
import org.junit.jupiter.api.Test;

/** Splitting, filtering and truncating a diff; pure functions, no network. */
class DiffPipelineTest {

    private static String fileDiff(String path, String body) {
        return "diff --git a/"
                + path
                + " b/"
                + path
                + "\n"
                + "index 111..222 100644\n"
                + "--- a/"
                + path
                + "\n"
                + "+++ b/"
                + path
                + "\n"
                + "@@ -1,1 +1,2 @@\n"
                + " keep\n"
                + "+"
                + body
                + "\n";
    }

    private static FileDiff file(String path) {
        return FileDiff.split(fileDiff(path, "x")).get(0);
    }

    // ---- FileDiff.split

    @Test
    void splitsOnePieceForEachFileAndKeepsTheTextExact() {
        String diff = fileDiff("A.java", "a") + fileDiff("dir/B.java", "b");

        List<FileDiff> files = FileDiff.split(diff);

        assertThat(files).extracting(FileDiff::path).containsExactly("A.java", "dir/B.java");
        assertThat(files.get(0).text() + files.get(1).text()).isEqualTo(diff);
    }

    @Test
    void emptyDiffGivesNoFiles() {
        assertThat(FileDiff.split("")).isEmpty();
        assertThat(FileDiff.split(null)).isEmpty();
    }

    @Test
    void codeLineThatLooksLikeAHeaderIsNotASplitPoint() {
        // Added lines start with "+", so this is content, not a new file.
        String diff = fileDiff("A.java", "diff --git a/fake b/fake");
        assertThat(FileDiff.split(diff)).hasSize(1);
    }

    @Test
    void readsPathOfDeletedAndBinaryFiles() {
        String deleted =
                "diff --git a/old.txt b/old.txt\ndeleted file mode 100644\nindex 1..0\n"
                        + "--- a/old.txt\n+++ /dev/null\n@@ -1 +0,0 @@\n-gone\n";
        String binary =
                "diff --git a/logo.png b/logo.png\nindex 1..2\nBinary files a/logo.png and b/logo.png differ\n";

        List<FileDiff> files = FileDiff.split(deleted + binary);

        assertThat(files).extracting(FileDiff::path).containsExactly("old.txt", "logo.png");
        assertThat(files.get(0).isDeleted()).isTrue();
        assertThat(files.get(1).isBinary()).isTrue();
    }

    // ---- DiffFilter

    @Test
    void keepsNormalSourceFiles() {
        assertThat(DiffFilter.isIgnored(file("src/main/App.java"))).isFalse();
        assertThat(DiffFilter.isIgnored(file("README.md"))).isFalse();
    }

    @Test
    void dropsLockfiles() {
        for (String p :
                List.of(
                        "package-lock.json",
                        "web/yarn.lock",
                        "pnpm-lock.yaml",
                        "go.sum",
                        "Cargo.lock",
                        "some/other.lock")) {
            assertThat(DiffFilter.isIgnored(file(p))).as(p).isTrue();
        }
    }

    @Test
    void dropsMinifiedAndGeneratedFilesByName() {
        for (String p : List.of("app.min.js", "style.min.css", "app.js.map", "api.pb.go")) {
            assertThat(DiffFilter.isIgnored(file(p))).as(p).isTrue();
        }
    }

    @Test
    void dropsFilesWithAGeneratedBanner() {
        String diff =
                "diff --git a/Gen.java b/Gen.java\n--- a/Gen.java\n+++ b/Gen.java\n"
                        + "@@ -0,0 +1,2 @@\n+// Code generated by protoc. DO NOT EDIT.\n+class Gen {}\n";
        assertThat(DiffFilter.isIgnored(FileDiff.split(diff).get(0))).isTrue();
    }

    @Test
    void dropsVendoredPathsButNotFilesThatMerelyHaveTheName() {
        assertThat(DiffFilter.isIgnored(file("node_modules/lib/index.js"))).isTrue();
        assertThat(DiffFilter.isIgnored(file("src/vendor/x.go"))).isTrue();
        assertThat(DiffFilter.isIgnored(file("dist/bundle.js"))).isTrue();
        assertThat(DiffFilter.isIgnored(file("src/vendor.java"))).isFalse();
    }

    @Test
    void dropsBinaryDeletedAndHunklessFiles() {
        assertThat(DiffFilter.isIgnored(file("logo.png"))).isTrue();
        String rename =
                "diff --git a/a.txt b/b.txt\nsimilarity index 100%\nrename from a.txt\nrename to b.txt\n";
        String deleted =
                "diff --git a/old.txt b/old.txt\ndeleted file mode 100644\n"
                        + "--- a/old.txt\n+++ /dev/null\n@@ -1 +0,0 @@\n-gone\n";
        String binary = "diff --git a/x b/x\nBinary files a/x and b/x differ\n";
        for (String d : List.of(rename, deleted, binary)) {
            assertThat(DiffFilter.isIgnored(FileDiff.split(d).get(0))).as(d).isTrue();
        }
    }

    @Test
    void relevantKeepsOnlyReviewableFilesInOrder() {
        List<FileDiff> all =
                FileDiff.split(
                        fileDiff("A.java", "a")
                                + fileDiff("package-lock.json", "l")
                                + fileDiff("B.java", "b"));

        assertThat(DiffFilter.relevant(all))
                .extracting(FileDiff::path)
                .containsExactly("A.java", "B.java");
    }

    // ---- DiffTruncator

    @Test
    void keepsEverythingWhenItFits() {
        List<FileDiff> files = FileDiff.split(fileDiff("A.java", "a") + fileDiff("B.java", "b"));

        DiffTruncator.Result r = DiffTruncator.fit(files, 10_000);

        assertThat(r.kept()).hasSize(2);
        assertThat(r.skippedPaths()).isEmpty();
    }

    @Test
    void neverCutsAFileInHalf() {
        String small = fileDiff("Small.java", "s");
        String big = fileDiff("Big.java", "b".repeat(500));
        List<FileDiff> files = FileDiff.split(small + big);

        DiffTruncator.Result r = DiffTruncator.fit(files, small.length() + 100);

        assertThat(r.kept()).extracting(FileDiff::path).containsExactly("Small.java");
        assertThat(r.skippedPaths()).containsExactly("Big.java");
        assertThat(r.joinedText()).isEqualTo(small);
    }

    @Test
    void aSmallerLaterFileStillFitsAfterAnOversizedOne() {
        String big = fileDiff("Big.java", "b".repeat(500));
        String small = fileDiff("Small.java", "s");

        DiffTruncator.Result r = DiffTruncator.fit(FileDiff.split(big + small), 300);

        assertThat(r.kept()).extracting(FileDiff::path).containsExactly("Small.java");
        assertThat(r.skippedPaths()).containsExactly("Big.java");
    }

    @Test
    void keptSizeNeverExceedsTheLimit() {
        List<FileDiff> files =
                FileDiff.split(
                        fileDiff("A.java", "a".repeat(100))
                                + fileDiff("B.java", "b".repeat(100))
                                + fileDiff("C.java", "c".repeat(100)));
        int limit = files.get(0).text().length() * 2 + 5;

        assertThat(DiffTruncator.fit(files, limit).joinedText().length())
                .isLessThanOrEqualTo(limit);
    }

    @Test
    void everythingSkippedWhenNoFileFits() {
        DiffTruncator.Result r = DiffTruncator.fit(FileDiff.split(fileDiff("A.java", "a")), 10);
        assertThat(r.kept()).isEmpty();
        assertThat(r.skippedPaths()).containsExactly("A.java");
    }
}
